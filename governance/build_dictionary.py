"""
build_dictionary.py — render metrics.yml into docs/DATA_DICTIONARY.md AND
validate it against the live warehouse.

Run: python governance/build_dictionary.py --db warehouse/mkt.duckdb

Exit code 1 if any metric references a model or column that does not exist.
Wire this into CI. Documentation that is not validated is documentation that
is wrong, and stale definitions are how two teams end up reporting different
MQL counts to the same executive.
"""
import argparse
import sys
from datetime import date

import duckdb
import yaml


def warehouse_index(con):
    rows = con.execute("""
        select table_schema, table_name, column_name
        from information_schema.columns
    """).fetchall()
    models, columns = {}, {}
    for schema, table, col in rows:
        models.setdefault(table, set()).add(schema)
        columns.setdefault(table, set()).add(col)
    return models, columns


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default="warehouse/mkt.duckdb")
    ap.add_argument("--spec", default="governance/metrics.yml")
    ap.add_argument("--out", default="docs/DATA_DICTIONARY.md")
    a = ap.parse_args()

    spec = yaml.safe_load(open(a.spec))
    con = duckdb.connect(a.db)
    models, columns = warehouse_index(con)

    errors = []
    lines = [
        "# Data Dictionary",
        "",
        f"Generated from `governance/metrics.yml` v{spec['version']} on {date.today()}.",
        "**Do not edit this file by hand** — edit the YAML and re-run "
        "`python governance/build_dictionary.py`.",
        "",
        f"- Owner: {spec['owner']}",
        f"- Review cadence: {spec['review_cadence']}",
        f"- Last reviewed: {spec['last_reviewed']}",
        "",
        "Every metric below is validated against the live warehouse at build "
        "time. If a model or column is renamed without updating this file, CI "
        "fails.",
        "",
        "---",
        "",
    ]

    for m in spec["metrics"]:
        name, model = m["name"], m.get("model")
        col = m.get("column")

        status = "verified"
        if model and model not in models:
            errors.append(f"metric '{name}': model '{model}' not found in warehouse")
            status = "MISSING MODEL"
        elif col and col not in columns.get(model, set()):
            errors.append(f"metric '{name}': column '{model}.{col}' not found")
            status = "MISSING COLUMN"

        lines += [
            f"## `{name}`",
            "",
            f"| | |",
            f"|---|---|",
            f"| **Layer** | {m.get('layer','—')} |",
            f"| **Model** | `{model or '—'}` |",
            f"| **Column** | {'`'+col+'`' if col else '—'} |",
            f"| **Grain** | {m.get('grain','—')} |",
            f"| **Owner** | {m.get('owner','—')} |",
            f"| **Warehouse check** | {status} |",
            "",
            "**Definition** — " + " ".join(m["definition"].split()),
            "",
        ]
        if m.get("rationale"):
            lines += ["**Why it is defined this way** — "
                      + " ".join(m["rationale"].split()), ""]
        if m.get("excludes"):
            lines += ["**Excludes**", ""] + [f"- {x}" for x in m["excludes"]] + [""]
        if m.get("known_limitations"):
            lines += ["**Known limitations**", ""] + \
                     [f"- {x}" for x in m["known_limitations"]] + [""]
        if m.get("governance_rule"):
            lines += ["**Governance rule** — "
                      + " ".join(m["governance_rule"].split()), ""]
        if m.get("changed"):
            lines += ["**Change log**", "", "| Date | Change | By |", "|---|---|---|"]
            lines += [f"| {c['date']} | {c['change']} | {c['by']} |" for c in m["changed"]]
            lines += [""]
        lines += ["---", ""]

    seg = spec.get("segments", {})
    if seg:
        lines += ["## Segment governance", ""]
        for k, v in seg.items():
            lines += [f"**{k.replace('_',' ').title()}** — " + " ".join(v.split()), ""]
        lines += ["---", ""]

    thr = spec.get("data_quality_thresholds", {})
    if thr:
        lines += ["## Data quality thresholds", "",
                  "Breaching `warn` shows a caution band on the dashboard. "
                  "Breaching `fail` blocks the build.", "",
                  "| Metric | Warn | Fail |", "|---|---|---|"]
        lines += [f"| `{k}` | {v['warn']:.0%} | {v['fail']:.0%} |" for k, v in thr.items()]
        lines += [""]

    with open(a.out, "w") as f:
        f.write("\n".join(lines))

    print(f"Wrote {a.out} ({len(spec['metrics'])} metrics)")
    if errors:
        print("\nVALIDATION FAILED:")
        for e in errors:
            print(f"  - {e}")
        sys.exit(1)
    print("All metric references validated against the warehouse.")


if __name__ == "__main__":
    main()
